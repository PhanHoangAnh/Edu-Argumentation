def load_module(root: Any, name: str | None = None) -> dict[str, Any]:
    """edu_server.py:load_module — packaged book first, then the legacy data/ shape. Cached by
    mtime so a re-import is picked up without a restart. Raises ValueError("Unknown book.")."""
    path = content.packaged_module_path(name)
    if path is None:
        try:
            path = content.resolve_data_module(name)
        except content.NotAFile as error:
            raise ValueError("Unknown book.") from error
    stamp = path.stat().st_mtime
    cached = _MODULE_CACHE.get(str(path))
    if cached and cached[0] == stamp:
        return cached[1]
    data = json.loads(path.read_text(encoding="utf-8"))
    _MODULE_CACHE[str(path)] = (stamp, data)
    return data


